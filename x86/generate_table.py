def instruction_allows_lock(instruction: Instruction, nmemonic: str) -> bool:
    lock_prefix_instructions =  ["ADC", "ADD", "AND", "BTC", "BTR", "BTS", "CMPXCHG", 
    "CMPXCHG8B", "CMPXCHG16B", "DEC", "INC", "NEG", "NOT", "OR", "SBB", "SUB", "XADD", "XCHG","XOR"]

    if nmemonic not in lock_prefix_instructions:
        return False

    # destination operand has to be a memory location
    if (instruction.op1 >= OperandType.RM8 and instruction.op1 <= OperandType.RM64):
        return True

    if (instruction.op1 >= OperandType.M8 and instruction.op1 <= OperandType.M64):
        return True

    return False

def instruction_allows_rep(nmemonic: str) -> bool:
    rep_instructions = ['INS','MOVS','OUTS','LODS','STOS']
    suffices = ['B','W', 'D', 'Q']

    for instr in rep_instructions:
       for suffix in suffices:
           if nmemonic == instr + suffix:
               return True
    return False

def instruction_allows_repe(nmemonic: str) -> bool:
    repe_instructions = ['CMPS', 'SCAS']
    suffices = ['B','W', 'D', 'Q']

    for instr in repe_instructions:
       for suffix in suffices:
           if nmemonic == instr + suffix:
               return True
    return False



instr_f = open("instructions.dat", "r")
instructions = {}
op_code_table = []
lines = instr_f.readlines() 

for line in lines:
    dash = line.find(chr(0x2014))
    if dash != -1:
        inst_name = line[:dash].strip()
        # many instructions that are seperated by a dash
        if "/" in inst_name:
            if ',' in inst_name:
                if 'MOVDQU' in inst_name:
                    instructions['MOVDQU'] = []
                    instructions['VMOVDQU'] = []
                elif 'MOVDQA' in inst_name:
                    instructions['MOVDQA'] = []
                    instructions['VMOVDQA'] = []
                else:
                    print(f"Unkown instruction: {inst_name}")
                continue
            for instr in inst_name.split('/'):
                if instr not in instructions and not instr[0].isdigit():
                    instructions[instr] = []
        else:
            if inst_name not in instructions:
                instructions[inst_name] = []
    else:
        op_row = line.split('|')
        encoding = op_row[0].strip()
        opcode = op_row[1].strip()
        operands= op_row[2].strip()

        # there is a formatting issue with ROUNDPS in instructions.dat
        if operands.startswith('/r ib'):
            opcode += ' ' + operands[:5]
            operands = operands[5:]

        parsed_instruction= parse_opcode(opcode)
        if parsed_instruction == None:
            print("Failed", opcode, operands, sep=" ")
            continue

        parsed_operands = parse_operands(operands)
        if parsed_operands != None:
            # for push and pop with FS and GS we actually need an operand either FS or GS
            if encoding == 'ZO' and not (parsed_operands.op1 == OperandType.FS or parsed_operands.op1 == OperandType.GS):
                parsed_instruction.op1 = 0 
                parsed_instruction.op2 = 0 
                parsed_instruction.op3 = 0 
            else:
                parsed_instruction.op1 = parsed_operands.op1 
                parsed_instruction.op2 = parsed_operands.op2
                parsed_instruction.op3 = parsed_operands.op3 

            parsed_instruction.encoding = f"OP_ENC_{encoding}"
 
            try:
                instructions[parsed_operands.nmemonic].append(parsed_instruction)
            except KeyError:
                instructions[parsed_operands.nmemonic] = [parsed_instruction]
instr_f.close()

# lock is not an instruction it is a prefix
# but it has its own opcode table so the extractor 
# interpets it as an instruction
instructions.pop('LOCK') 
# rep,repe,repne
# these instructions take have zero operands but have different encodings
# depending on the the size. All these have alternative nmemonics that 
# contain information about the size (ins -> insb,insw,insd,insq)
instructions.pop('INS')
instructions.pop('MOVS')
instructions.pop('OUTS')
instructions.pop('LODS')
instructions.pop('STOS')
instructions.pop('CMPS')
instructions.pop('SCAS')  

# if an instruction has no variants remove it
keys_to_remove = []
for nm in instructions:
    if len(instructions[nm]) == 0:
        keys_to_remove.append(nm)

for key in keys_to_remove:
    instructions.pop(key)

# remove redundant enter encodings
variants_to_remove = []
for variant in instructions["ENTER"]:
    if variant.op2 == OperandType.NOP:
        variants_to_remove.append(variant)

for variant in variants_to_remove:
    instructions["ENTER"].remove(variant)


# it is discouraged to use these variants
# just use regular mov
variants_to_remove = []
for variant in instructions["MOVSXD"]:
    if variant.op1 == OperandType.R16 and variant.op2 == OperandType.RM16:
        variants_to_remove.append(variant)
    elif variant.op1 == OperandType.R32 and variant.op2 == OperandType.RM32:
        variants_to_remove.append(variant)

for variant in variants_to_remove:
    instructions["MOVSXD"].remove(variant)


# imm8 will get sign extended to 16/32/64 bits 
# change the operand to simm8 to prevent mistakes
for variant in instructions["CMP"]:
    if variant.op2 == OperandType.IMM8:
        op1 = variant.op1
        if op1 == OperandType.RM16 or op1 == OperandType.R32 or op1 == OperandType.R64:
            variant.op2 = OperandType.SIMM8

# ensure the 8 bit immediate is sign extended
for variant in instructions["IMUL"]:
    if variant.op3 == OperandType.IMM8:
            variant.op3 = OperandType.SIMM8 

sorted_instructions = sorted(instructions)
gperf_file.write("const Instruction INSTRUCTION_TABLE[] = {\n")

instr_variant_lookup = []
current_index = 0
instruction_table_size = 0
for i, mnemonic in enumerate(sorted_instructions):
    variant_count = len(instructions[mnemonic])
    instr_variant_lookup.append(current_index)
    instructions[mnemonic].sort(key=lambda var: var.get_size())
    for instr_variant in instructions[mnemonic]:
        if instruction_allows_lock(instr_variant, mnemonic):
            instr_variant.lock = 1

        if instruction_allows_rep(mnemonic):
            instr_variant.rep = 1

        if instruction_allows_repe(mnemonic):
            instr_variant.repe = 1

        gperf_file.write(instr_variant.to_c_struct(variant_count) + '\n')
        current_index += 1
        instruction_table_size += 1 
gperf_file.write("};\n")
gperf_file.write("%}\n")

